package com.cuonglm.ecommerce.backend.attribute.enums;

/**
 * AttributeStatus – Các trạng thái có thể có của Attribute
 *
 * <p>
 * ACTIVE: Đang hoạt động, được hiển thị cho người bán khi tạo Product mới.
 * <br>
 * ARCHIVED: Đã lưu trữ, không hiển thị cho việc tạo Product mới, nhưng dữ liệu cũ vẫn được giữ.
 * </p>
 *
 * @author cuonglmptit
 * @since Tuesday, 02 December 2025
 */
public enum AttributeStatus {
    ACTIVE,
    ARCHIVED
}
